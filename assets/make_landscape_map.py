"""Turn the landscape pages' star tables into the numeric tables the map is drawn from.

Module summary
--------------
``LANDSCAPE.md`` and ``PAYSAGE.md`` rate every tool from one star to five. A
positioning map needs numbers, and the obvious way to get them -- keep a second
copy of the ratings in a comma-separated-values file -- is the defect this
repository keeps catching in its own prose: two copies of one fact, and nobody
able to say which is current when they disagree.

So the comma-separated-values files are derived. This reads the star table out
of each page, counts the stars, and writes the numbers next to this file. The
map is then drawn from those by `standpoint <https://github.com/warith-harchaoui/standpoint>`_,
which runs a principal component analysis over the ratings and names the two
axes it finds. The command is printed rather than run, because naming the axes
needs a local model and a figure should not be regenerated by a test.

Usage example
-------------
>>> ratings, criteria = read("LANDSCAPE.md")
>>> criteria[0]
'Per-unit model'
>>> ratings["saggio"][0]
5

Author
------
Warith Harchaoui
"""

from __future__ import annotations

import pathlib
from typing import Final

#: Repository root, from this file rather than from the working directory.
ROOT: Final[pathlib.Path] = pathlib.Path(__file__).resolve().parents[1]

#: Each page, and the stem its numeric table and its map are written under.
PAGES: Final[dict[str, str]] = {"LANDSCAPE.md": "landscape.en", "PAYSAGE.md": "landscape.fr"}

#: The tool the map is oriented around: it is placed top-right so that two maps
#: of the same table, drawn in two languages, can be read against each other.
REFERENCE: Final[str] = "saggio"


def read(page: str) -> tuple[dict[str, list[int]], list[str]]:
    """Return one page's ratings and the criteria they are against.

    Parameters
    ----------
    page : str
        File name, relative to the repository root.

    Returns
    -------
    tuple
        A mapping of tool name to its ratings, in column order, and the column
        names.

    Examples
    --------
    >>> ratings, criteria = read("PAYSAGE.md")
    >>> len(criteria) == len(ratings["saggio"])
    True
    """
    lines = (ROOT / page).read_text(encoding="utf-8").splitlines()
    start = next(index for index, line in enumerate(lines) if line.startswith("| |"))
    cells = [cell.strip() for cell in lines[start].strip().strip("|").split("|")]
    criteria = cells[1:]
    ratings: dict[str, list[int]] = {}
    for line in lines[start + 2 :]:
        if not line.startswith("|"):
            break
        row = [cell.strip() for cell in line.strip().strip("|").split("|")]
        ratings[row[0].replace("**", "").strip()] = [cell.count("⭐") for cell in row[1:]]
    return ratings, criteria


def comma_separated(page: str) -> str:
    """Return one page's table as comma-separated values.

    A criterion is never quoted away: the column names are written as they
    appear on the page, and a comma inside one would silently add a column, so
    every field is quoted.

    Examples
    --------
    >>> comma_separated("LANDSCAPE.md").splitlines()[0].startswith('"Tool"')
    True
    """
    ratings, criteria = read(page)
    head = ["Tool" if page == "LANDSCAPE.md" else "Outil", *criteria]
    rows = ['","'.join(head)]
    for name, scores in ratings.items():
        rows.append('","'.join([name, *(str(score) for score in scores)]))
    return "\n".join(f'"{row}"' for row in rows) + "\n"


def main() -> None:
    """Write both numeric tables, and print the two commands that draw the maps."""
    here = pathlib.Path(__file__).resolve().parent
    for page, stem in PAGES.items():
        (here / f"{stem}.csv").write_text(comma_separated(page), encoding="utf-8")
        print(f"assets/{stem}.csv")
    print()
    for stem in PAGES.values():
        print(
            f"standpoint assets/{stem}.csv -r {REFERENCE} -o assets "
            f"--stem {stem.replace('.en', '').replace('.fr', '')}"
            f"{'' if stem.endswith('.en') else '.fr'} --model qwen3:8b"
        )


if __name__ == "__main__":
    main()
